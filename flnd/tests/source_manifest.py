"""The source manifest: what `src/sources/_manifest.py` holds, made from the sources themselves.

    make manifest                            # write src/sources/_manifest.py and the extension's
    uv run python tests/source_manifest.py   # print the first instead

The manifest lets `flnd --help`, `flnd sources` and target resolution know each built-in source
(its code, name, domains, target forms and categories) without importing it. Importing the
seven sources costs tens of milliseconds (the source API and the sources' own tables), which `--help`
can't afford. The manifest is generated, never edited: `tests/test_manifest.py` checks that the
file matches what this module makes from the code, so a change to a source's routes fails the
tests until `make manifest` is run.

How the file is made:
1. `entries` imports each class of `flnd.sources.BUILT_IN`, in its order.
2. Each source becomes one dictionary of plain values: tuples of strings, nothing to import.
3. `render` writes them as a Python module whose only name is `SOURCES`, formatted the same on
   every OS and every Python from 3.11.
4. `extension` sets the `host_permissions` of `src/extension/manifest.json` to the built-ins'
   domains, so Chrome lets the extension read them (src/docs/extension.md).
"""

from __future__ import annotations

import argparse
import importlib
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "src" / "sources" / "_manifest.py"
EXTENSION = ROOT / "src" / "extension" / "manifest.json"

HEADER = '''"""Every built-in source, as plain data: read by `flnd --help` and target resolution.

src/docs/writing-a-source explains it.

Generated by `make manifest` (tests/source_manifest.py) from the sources themselves; never edit
it by hand. `tests/test_manifest.py` fails when it no longer matches the code.

Each entry, by the source's code:
- `module` and `cls`: where the source's class is, so `flnd.sources.SOURCES` imports one source
  only when it is used;
- `name`: the site's name, as people know it;
- `domains`: the hosts a link must be on for the source to read it;
- `forms`: each way to write one of its targets, as `--help` lists them;
- `categories`: what `--only` may name for it;
- `logins`: the ways `flnd login <code>` can log in to it.
"""

'''


def entries() -> dict[str, dict[str, Any]]:
    """Each built-in source's manifest entry, in the registry's order.

    Returns:
        The entries by code; every value is a string or a tuple of strings.
    """
    sys.path.insert(0, str(ROOT))
    from flnd.sources import BUILT_IN

    found: dict[str, dict[str, Any]] = {}
    for module, name in BUILT_IN:
        source = getattr(importlib.import_module(module), name)
        found[source.code] = {
            "module": source.__module__,
            "cls": source.__name__,
            "name": source.name,
            "domains": tuple(source.domains),
            "forms": tuple(source.forms),
            "categories": tuple(source.categories),
            "logins": tuple(source.login.methods) if source.login is not None else (),
        }
    return found


def render() -> str:
    """The text of `src/sources/_manifest.py`, as it should be."""
    lines = [HEADER.rstrip("\n") + "\n", "SOURCES: dict[str, dict[str, object]] = {"]
    for code, entry in entries().items():
        lines.append(f"    {code!r}: {{")
        for key, value in entry.items():
            if isinstance(value, tuple):
                lines.append(f"        {key!r}: (")
                lines.extend(f"            {item!r}," for item in value)
                lines.append("        ),")
            else:
                lines.append(f"        {key!r}: {value!r},")
        lines.append("    },")
    lines.append("}")
    return "\n".join(lines) + "\n"


def extension() -> str:
    """The text of `src/extension/manifest.json`, its `host_permissions` the built-ins' domains."""
    manifest = json.loads(EXTENSION.read_text(encoding="utf-8"))
    domains = dict.fromkeys(domain for entry in entries().values() for domain in entry["domains"])
    manifest["host_permissions"] = [f"*://*.{domain}/*" for domain in domains]
    return json.dumps(manifest, indent=2) + "\n"


def main(argv: list[str] | None = None) -> None:
    """Print the manifest, or write it and the extension's with `--write`."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true", help=f"write {MANIFEST.name}")
    args = parser.parse_args(argv)
    text = render()
    if args.write:
        MANIFEST.write_text(text, encoding="utf-8", newline="\n")
        EXTENSION.write_text(extension(), encoding="utf-8", newline="\n")
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()

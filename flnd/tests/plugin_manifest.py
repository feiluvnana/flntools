"""The plugin manifest: what `src/plugins/_manifest.py` holds, made from the built-in plugins.

    make manifest                            # write src/plugins/_manifest.py and the extension's
    uv run python tests/plugin_manifest.py   # print the first instead

The manifest lets `flnd --help`, `flnd sources` and target resolution know each built-in plugin
(its code, name, domains, routes, target forms and categories) without importing it: importing
the plugins costs tens of milliseconds, which `--help` can't afford. It is generated, never
edited: `tests/test_manifest.py` checks that the file matches what this module makes from the
code, so a change to a plugin's routes fails the tests until `make manifest` is run.

How the file is made:
1. `entries` imports each class of `flnd.plugins.BUILT_IN`, in its order.
2. Each plugin becomes one dictionary of plain values (`flnd.plugins.facts`, which
   `plugins.json` holds for an installed plugin too, plus where its class is, its forms,
   categories and login methods): nothing to import.
3. `render` writes them as a Python module whose only name is `PLUGINS`, formatted the same on
   every OS and every Python from 3.11.
4. `extension` sets the `host_permissions` of `src/extension/manifest.json` to the built-ins'
   domains, so Chrome lets the extension read them (src/docs/extension.md).
"""

from __future__ import annotations

import argparse
import importlib
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "src" / "plugins" / "_manifest.py"
EXTENSION = ROOT / "src" / "extension" / "manifest.json"

HEADER = '''"""Every built-in plugin, as plain data: read by `flnd --help` and target resolution.

src/docs/writing-a-plugin explains it.

Generated by `make manifest` (tests/plugin_manifest.py) from the plugins themselves; never edit
it by hand. `tests/test_manifest.py` fails when it no longer matches the code.

Each entry, by the plugin's code:
- `module` and `cls`: where the plugin's class is, so `flnd.plugins.PLUGINS` imports one
  plugin only when it is used;
- `name`, `domains`, `routes` and `unsupported`: `flnd.plugins.facts`, what resolving reads;
- `forms`: each way to write one of its targets, as `--help` lists them;
- `categories`: what `--only` may name for it;
- `logins`: the ways `flnd login <code>` can log in to it.
"""

'''


def _facts(cls: Any) -> dict[str, Any]:
    """What resolving and help read of a plugin without importing it, as plain data."""
    return {
        "name": cls.name, "domains": list(cls.domains),
        "routes": [{"name": known.kind, "single": known.single, "discovers": known.discovers,
                    "shown": known.shown,
                    "patterns": [list(item) if isinstance(item, tuple) else item
                                 for item in known.patterns],
                    "categories": [{"name": category.name, "own": category.own}
                                   for category in known.categories]}
                   for known in cls.routes],
        "unsupported": dict(cls.unsupported),
    }


def entries() -> dict[str, dict[str, Any]]:
    """Each built-in plugin's manifest entry, in the registry's order."""
    sys.path.insert(0, str(ROOT))
    from flnd.plugins import BUILT_IN

    found: dict[str, dict[str, Any]] = {}
    for module, name in BUILT_IN:
        plugin = getattr(importlib.import_module(module), name)
        found[plugin.code] = {
            "module": plugin.__module__, "cls": plugin.__name__, **_facts(plugin),
            "forms": list(plugin.forms), "categories": list(plugin.categories),
            "logins": list(plugin.login.methods) if plugin.login is not None else [],
        }
    return found


def render() -> str:
    """The text of `src/plugins/_manifest.py`, as it should be."""
    return f"{HEADER}PLUGINS: dict[str, dict[str, object]] = {_literal(entries(), 0)}\n"


def _literal(value: Any, indent: int, start: int = 0) -> str:
    """`value` as Python source, its first line starting at column `start` (its own indent
    when 0): on one line when it fits in 100 columns, else one item a line, indented 4 more;
    a long text is adjacent literals, one a line, in parentheses, which Python joins."""
    flat = repr(value)
    if max(start, indent) + len(flat) + 1 <= 100 or not value:
        return flat
    pad = " " * (indent + 4)
    if isinstance(value, str):
        pieces = [""]
        for char in value:
            if len(repr(pieces[-1] + char)) > 100 - len(pad):
                pieces.append("")
            pieces[-1] += char
        return "(\n" + "\n".join(pad + repr(piece) for piece in pieces) + ")"
    if isinstance(value, dict):
        items = [f"{pad}{key!r}: {_literal(item, indent + 4, len(pad) + len(repr(key)) + 2)},"
                 for key, item in value.items()]
        return "{\n" + "\n".join(items) + "\n" + " " * indent + "}"
    items = [f"{pad}{_literal(item, indent + 4)}," for item in value]
    return "[\n" + "\n".join(items) + "\n" + " " * indent + "]"


def extension() -> str:
    """The text of `src/extension/manifest.json`, its `host_permissions` the built-ins' domains."""
    manifest = json.loads(EXTENSION.read_text(encoding="utf-8"))
    domains = dict.fromkeys(domain for entry in entries().values() for domain in entry["domains"])
    manifest["host_permissions"] = [f"*://*.{domain}/*" for domain in domains]
    return json.dumps(manifest, indent=2) + "\n"


def main(argv: list[str] | None = None) -> None:
    """Print the manifest, or write it and the extension's with `--write`."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true", help=f"write {MANIFEST.name}")
    args = parser.parse_args(argv)
    text = render()
    if args.write:
        MANIFEST.write_text(text, encoding="utf-8", newline="\n")
        EXTENSION.write_text(extension(), encoding="utf-8", newline="\n")
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
